'use strict';
// Regenerates syntaxes/game-basic.tmLanguage.json from src/keywords.js.
//   node scripts/build-grammar.js
const fs = require('fs');
const path = require('path');
const K = require('../src/keywords');

const esc = (w) => w.replace(/\$/g, '\\$');
// Longest first so MID$ wins over MID, and so on.
const alt = (list) => [...list].sort((a, b) => b.length - a.length).map(esc).join('|');
// A word ending in $ can't use a trailing \b, so build the boundary by hand.
const TARGET = '(?:\\d+|\\*[A-Za-z_][A-Za-z0-9_]*)';
const TARGETS = `(${TARGET}(?:\\s*,\\s*${TARGET})*)`;
const word = (list) => `(?<![A-Za-z0-9_$%!#@])(?i:${alt(list)})(?![A-Za-z0-9_])`;
const LABEL = '\\*[A-Za-z_][A-Za-z0-9_]*';

const grammar = {
  $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
  name: 'GAME BASIC',
  scopeName: 'source.game-basic',
  comment: 'GAME BASIC for SEGASATURN. Generated by scripts/build-grammar.js; edit src/keywords.js instead.',
  patterns: [
    { include: '#include-directive' },
    { include: '#line-start' },
    { include: '#statement' },
  ],
  repository: {
    'include-directive': {
      comment: 'BASTERM-only #include "FILE.B", written without a line number',
      match: '(?i)^\\s*(#include)\\s+("[^"]*")',
      captures: {
        1: { name: 'keyword.control.directive.include.game-basic' },
        2: { name: 'string.quoted.double.include.game-basic' },
      },
    },
    'line-start': {
      comment: 'Optional line number, then an optional *label definition',
      match: `^\\s*(?:(\\d+)\\s*(${LABEL})?|(${LABEL}))`,
      captures: {
        1: { name: 'constant.numeric.line-number.game-basic' },
        2: { name: 'entity.name.label.game-basic' },
        3: { name: 'entity.name.label.game-basic' },
      },
    },
    statement: {
      patterns: [
        { include: '#data-statement' },
        { include: '#comment' },
        { include: '#string' },
        { include: '#object-field' },
        { include: '#jump-target' },
        { include: '#number' },
        { include: '#keyword-control' },
        { include: '#keyword-operator-word' },
        { include: '#function' },
        { include: '#keyword-statement' },
        { include: '#print-shorthand' },
        { include: '#variable' },
        { include: '#operator' },
        { include: '#punctuation' },
      ],
    },
    'data-statement': {
      comment: "DATA items are literal up to ':'; a ' inside them is data, not a comment",
      begin: '(?<![A-Za-z0-9_$])(?i:DATA)(?![A-Za-z0-9_$])',
      beginCaptures: { 0: { name: 'keyword.other.statement.game-basic' } },
      end: '(?=:)|$',
      name: 'meta.data.game-basic',
      patterns: [
        { include: '#string' },
        { include: '#number' },
        { match: ',', name: 'punctuation.separator.game-basic' },
      ],
    },
    comment: {
      patterns: [
        {
          begin: "'",
          end: '$',
          name: 'comment.line.apostrophe.game-basic',
        },
        {
          begin: '(?<![A-Za-z0-9_$])(?i:REM)(?![A-Za-z0-9_$])',
          beginCaptures: { 0: { name: 'keyword.other.rem.game-basic' } },
          end: '$',
          name: 'comment.line.rem.game-basic',
        },
      ],
    },
    string: {
      comment: 'BASIC strings may run to the end of the line without a closing quote',
      begin: '"',
      end: '"|$',
      name: 'string.quoted.double.game-basic',
    },
    'object-field': {
      comment: 'OBJ(n,@ATR) style field names',
      match: '@[A-Za-z_][A-Za-z0-9_]*',
      name: 'constant.language.object-field.game-basic',
    },
    'jump-target': {
      comment: 'Line numbers and *labels after GOTO, GOSUB, THEN, RESTORE and friends',
      patterns: [
        {
          match: `(${word(K.JUMP_WORDS.filter((w) => K.CONTROL.includes(w)))})\\s*${TARGETS}`,
          captures: {
            1: { name: 'keyword.control.game-basic' },
            2: { patterns: [{ include: '#jump-list' }] },
          },
          name: 'meta.jump.game-basic',
        },
        {
          match: `(${word(K.JUMP_WORDS.filter((w) => !K.CONTROL.includes(w)))})\\s*${TARGETS}`,
          captures: {
            1: { name: 'keyword.other.statement.game-basic' },
            2: { patterns: [{ include: '#jump-list' }] },
          },
          name: 'meta.jump.game-basic',
        },
      ],
    },
    'jump-list': {
      patterns: [
        { match: '\\d+', name: 'constant.numeric.line-reference.game-basic' },
        { match: LABEL, name: 'entity.name.label.reference.game-basic' },
        { match: ',', name: 'punctuation.separator.game-basic' },
      ],
    },
    number: {
      patterns: [
        {
          comment: 'Hex, with an optional fixed-point fraction: &H1F, &H0.0E, &HFFFF.FFFC',
          match: '(?i)&H(?:[0-9A-F]+(?:\\.[0-9A-F]*)?|\\.[0-9A-F]+)',
          name: 'constant.numeric.hex.game-basic',
        },
        {
          comment: 'Binary, with an optional fixed-point fraction: &B101, &B101.01 (no octal in GAME BASIC)',
          match: '(?i)&B(?:[01]+(?:\\.[01]*)?|\\.[01]+)',
          name: 'constant.numeric.binary.game-basic',
        },
        {
          match: '(?i)(?<![A-Za-z0-9_$%!#.])(?:\\d+\\.?\\d*|\\.\\d+)(?:E[+-]?\\d+)?[!#%]?',
          name: 'constant.numeric.decimal.game-basic',
        },
      ],
    },
    'keyword-control': { match: word(K.CONTROL), name: 'keyword.control.game-basic' },
    'keyword-operator-word': { match: word(K.OPERATORS), name: 'keyword.operator.word.game-basic' },
    function: {
      // OBJ, PALETTE and TPROP are mostly statements, so colour them as such.
      match: word(K.FUNCTIONS.filter((w) => !K.DUAL.includes(w) || w === 'MID$')),
      name: 'support.function.builtin.game-basic',
    },
    'keyword-statement': { match: word(K.STATEMENTS), name: 'keyword.other.statement.game-basic' },
    'print-shorthand': { match: '\\?', name: 'keyword.other.statement.print.game-basic' },
    variable: {
      match: '[A-Za-z][A-Za-z0-9_]*[$%!#]?',
      name: 'variable.other.game-basic',
    },
    operator: {
      patterns: [
        { match: '<=|>=|<>|><|=<|=>|[<>=]', name: 'keyword.operator.comparison.game-basic' },
        { match: '[-+*/\\\\^]', name: 'keyword.operator.arithmetic.game-basic' },
      ],
    },
    punctuation: {
      patterns: [
        { match: ':', name: 'punctuation.separator.statement.game-basic' },
        { match: '[,;]', name: 'punctuation.separator.game-basic' },
        { match: '[()]', name: 'punctuation.parenthesis.game-basic' },
      ],
    },
  },
};

const out = path.join(__dirname, '..', 'syntaxes', 'game-basic.tmLanguage.json');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(grammar, null, 2) + '\n');
console.log(`wrote ${path.relative(process.cwd(), out)}`);
